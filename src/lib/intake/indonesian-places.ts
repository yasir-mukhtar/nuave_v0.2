/**
 * Up to `limit` places that start with the typed text (then those containing
 * it), skipping ones already chosen. Case and spacing do not matter.
 */
export function placeSuggestions(
  typed: string,
  chosen: readonly string[],
  limit = 3,
): string[] {
  const query = typed.trim().toLocaleLowerCase("id-ID");
  if (!query) return [];
  const taken = new Set(chosen.map((item) => item.toLocaleLowerCase("id-ID")));
  const unique = [...new Set(INDONESIAN_PLACES)].filter(
    (place) => !taken.has(place.toLocaleLowerCase("id-ID")),
  );
  const starts = unique.filter((place) =>
    place.toLocaleLowerCase("id-ID").startsWith(query),
  );
  const contains = unique.filter(
    (place) =>
      !starts.includes(place) &&
      place.toLocaleLowerCase("id-ID").includes(query),
  );
  return [...starts, ...contains].slice(0, limit);
}
